function getStatusInfo(status, error) {
  if (error > 0) return { label: 'Error', class: 'error', icon: 'alert' };
  return STATUS_MAP[status] || STATUS_MAP[0];
}

function formatBytes(bytes, decimals = 1) {
  if (bytes === 0) return '0 B';
  const k = 1024;
  const sizes = ['B', 'KB', 'MB', 'GB', 'TB'];
  const i = Math.floor(Math.log(bytes) / Math.log(k));
  return parseFloat((bytes / Math.pow(k, i)).toFixed(decimals)) + ' ' + sizes[i];
}

function formatSpeed(bytesPerSec) {
  if (bytesPerSec === 0) return '—';
  return formatBytes(bytesPerSec) + '/s';
}

function formatEta(seconds) {
  if (seconds < 0) return '∞';
  if (seconds === 0) return '—';
  const h = Math.floor(seconds / 3600);
  const m = Math.floor((seconds % 3600) / 60);
  const s = seconds % 60;
  if (h > 24) {
    const d = Math.floor(h / 24);
    return `${d}d ${h % 24}h`;
  }
  if (h > 0) return `${h}h ${m}m`;
  if (m > 0) return `${m}m ${s}s`;
  return `${s}s`;
}

function formatPercent(ratio) {
  return (ratio * 100).toFixed(1) + '%';
}

function formatRatio(ratio) {
  if (ratio < 0) return '—';
  return ratio.toFixed(2);
}

function formatDate(unixTs) {
  if (!unixTs || unixTs === 0) return '—';
  const d = new Date(unixTs * 1000);
  return d.toLocaleDateString(undefined, { month: 'short', day: 'numeric', year: 'numeric' });
}

function formatDateRelative(unixTs) {
  if (!unixTs || unixTs === 0) return '—';
  const now = Date.now() / 1000;
  const diff = now - unixTs;
  if (diff < 60) return 'just now';
  if (diff < 3600) return `${Math.floor(diff/60)}m ago`;
  if (diff < 86400) return `${Math.floor(diff/3600)}h ago`;
  if (diff < 604800) return `${Math.floor(diff/86400)}d ago`;
  return formatDate(unixTs);
}

function extractTorrentName(magnetUri) {
  try {
    const url = new URL(magnetUri);
    const dn = url.searchParams.get('dn');
    return dn ? decodeURIComponent(dn) : 'Unknown Torrent';
  } catch {
    return 'Unknown Torrent';
  }
}

function minutesToTime(minutes) {
  const h = Math.floor(minutes / 60);
  const m = minutes % 60;
  return `${String(h).padStart(2, '0')}:${String(m).padStart(2, '0')}`;
}

function timeToMinutes(timeStr) {
  const [h, m] = timeStr.split(':').map(Number);
  return h * 60 + m;
}

